export default function ThemeToggle({ theme, onToggle }) {
  const dark = theme === "dark";
  return (
    <button
      type="button"
      onClick={onToggle}
      aria-label={dark ? "Switch to light mode" : "Switch to dark mode"}
      title={dark ? "Switch to light mode" : "Switch to dark mode"}
      className="cursor-pointer touch-manipulation rounded-full border border-slate-300 bg-slate-100 p-3 text-slate-600 select-none transition hover:bg-slate-200 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-violet-500 dark:border-white/10 dark:bg-white/[0.06] dark:text-amber-200 dark:hover:bg-white/10"
    >
      {dark ? <SunIcon /> : <MoonIcon />}
    </button>
  );
}
